#!/usr/bin/env python
"""Turn official Artemis candidate-region polygons into a site registry.

Each output site is one representative interior point computed from the
polygon, NOT a certified landing coordinate. The script refuses to guess:

  * every output point must lie inside its polygon;
  * computed polygon area must match the source `Area_km2` property;
  * non-Polygon geometry and unclosed rings are errors.

Example (after downloading the NASA-derived nine-region GeoJSON):

    python scripts/prepare_sites.py \
        backend/data/A3_9regions-lonlat-simplified.geojson \
        backend/data/sites_real.json

The raw GeoJSON is a downloaded data product and is git-ignored; the small
JSON registry this script writes can be reviewed and committed.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from backend.dem import DEM  # noqa: E402

DEFAULT_SOURCE_URL = (
    "https://www.nasa.gov/news-release/nasa-provides-update-on-artemis-iii-moon-landing-regions/"
)


def _ring_xy(ring: list[list[float]]) -> tuple[np.ndarray, np.ndarray]:
    arr = np.asarray(ring, dtype=float)
    if arr.ndim != 2 or arr.shape[1] < 2:
        raise ValueError("ring must be a list of [lon, lat] pairs")
    if len(arr) < 4 or not np.allclose(arr[0, :2], arr[-1, :2]):
        raise ValueError("ring must be closed and have at least three distinct vertices")
    lon, lat = arr[:, 0], arr[:, 1]
    return DEM.project(lat, lon)


def _shoelace_centroid(x: np.ndarray, y: np.ndarray) -> tuple[float, float, float]:
    """Area (m^2) and centroid (x, y) of a closed ring, excluding the duplicate end."""
    x, y = x[:-1], y[:-1]
    x2, y2 = np.roll(x, -1), np.roll(y, -1)
    cross = x * y2 - x2 * y
    area2 = float(cross.sum())
    if abs(area2) < 1e-9:
        raise ValueError("polygon has zero projected area")
    cx = float(((x + x2) * cross).sum() / (3.0 * area2))
    cy = float(((y + y2) * cross).sum() / (3.0 * area2))
    return abs(area2) / 2.0, cx, cy


def _contains(x: np.ndarray, y: np.ndarray, px: float, py: float) -> bool:
    """Ray-casting point-in-polygon test in projected metres."""
    inside = False
    j = len(x) - 1
    for i in range(len(x)):
        if ((y[i] > py) != (y[j] > py)) and (
            px < (x[j] - x[i]) * (py - y[i]) / (y[j] - y[i]) + x[i]
        ):
            inside = not inside
        j = i
    return inside


def sites_from_geojson(path: Path, source_url: str) -> dict:
    raw = json.loads(path.read_text(encoding="utf-8"))
    features = raw.get("features")
    if not isinstance(features, list) or not features:
        raise ValueError("expected a GeoJSON FeatureCollection with features")

    sites = []
    for feat in features:
        props = feat.get("properties") or {}
        geom = feat.get("geometry") or {}
        if geom.get("type") != "Polygon":
            raise ValueError(
                f"region {props.get('Region', '?')!r}: expected Polygon, "
                f"got {geom.get('type')!r}"
            )
        ring = geom.get("coordinates", [[]])[0]
        x, y = _ring_xy(ring)
        area_m2, cx, cy = _shoelace_centroid(x, y)

        if not _contains(x, y, cx, cy):
            raise ValueError(
                f"region {props.get('Region', '?')!r}: centroid falls outside its polygon"
            )

        expected = props.get("Area_km2")
        if expected is not None and abs(area_m2 / 1e6 - float(expected)) > 0.01 * float(expected):
            raise ValueError(
                f"region {props.get('Region', '?')!r}: projected area {area_m2 / 1e6:.3f} km^2 "
                f"does not match source Area_km2 {expected}"
            )

        lat, lon = DEM.unproject(cx, cy)
        code = str(props.get("RegionCode") or "").strip()
        if not code:
            raise ValueError(f"region {props.get('Region', '?')!r}: missing RegionCode")

        name = str(props.get("Region") or code).strip()
        area_km2 = area_m2 / 1e6
        sites.append({
            "id": "a3_" + code.lower(),
            "name": name,
            "lat": round(float(lat), 5),
            "lon": round(float(lon), 5),
            "verified": False,
            "note": (
                f"Representative interior point computed from the official 2024 NASA "
                f"nine-region polygon (region code {code}, {area_km2:.1f} km^2); "
                "not a certified landing coordinate."
            ),
            "representative": True,
            "source": (
                "NASA Artemis III candidate landing regions, 2024 down-selection; "
                "polygon A3_9regions-lonlat-simplified.geojson"
            ),
        })

    return {
        "_comment": (
            "Generated by scripts/prepare_sites.py from official-derived region polygons. "
            "Each point is a representative interior point, not a certified landing coordinate."
        ),
        "source_url": source_url,
        "polygon_file": path.name,
        "sites": sites,
    }


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("geojson", type=Path, help="official-derived region polygons")
    ap.add_argument("output", type=Path, help="site registry JSON to write")
    ap.add_argument("--source-url", default=DEFAULT_SOURCE_URL,
                    help="metadata URL recorded in the output")
    args = ap.parse_args(argv)

    try:
        payload = sites_from_geojson(args.geojson, args.source_url)
    except (OSError, ValueError, KeyError) as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, ensure_ascii=False) + "\n",
                           encoding="utf-8")
    print(f"{'region':24s} {'code':5s} {'lat':>10s} {'lon':>10s}")
    for s in payload["sites"]:
        print(f"{s['name']:24s} {s['id'][3:].upper():5s} {s['lat']:10.5f} {s['lon']:10.5f}")
    print(f"wrote {len(payload['sites'])} representative sites to {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
